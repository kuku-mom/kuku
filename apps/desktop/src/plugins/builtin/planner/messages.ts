export function pt(key: keyof typeof messages): string {
  const locale = currentLocale();
  return messages[key][locale === "ko" ? 0 : locale === "ja" ? 2 : 1];
}
export function providerName(provider: string): string {
  return provider === "google"
    ? "Google Calendar"
    : provider === "apple-calendar"
      ? "Apple Calendar"
      : `Apple ${pt("reminders")}`;
}
